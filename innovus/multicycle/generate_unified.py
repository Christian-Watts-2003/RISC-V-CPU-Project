#!/usr/bin/env python3
"""Generate the standalone multicycle ASIC sources from the project RTL."""

import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent
PARTS = ("controller", "imm_gen", "alu", "branch_unit", "lsu", "regfile")
CONFIGS = (
    ("multicycle_unoptimized.v", "unoptimized", None),
    ("multicycle_predecode.v", "predecode only", (1, 0)),
    ("multicycle_or_select.v", "OR selection only", (0, 1)),
    ("multicycle_optimized.v", "predecode and OR selection", (1, 1)),
)


def replace_once(text, old, new, description):
    if text.count(old) != 1:
        raise ValueError(f"Expected exactly one {description}")
    return text.replace(old, new, 1)


def shared_parts():
    parts = []
    for name in PARTS:
        baseline = (ROOT / "CURRENT_multicycle" / "rtl" / f"{name}.sv").read_text()
        experiment = (ROOT / "OPTIMIZED_multicycle" / "rtl" / f"{name}.sv").read_text()
        if baseline != experiment:
            raise ValueError(f"Shared RTL differs between projects: {name}")
        if name == "regfile":
            baseline = replace_once(
                baseline,
                "    integer i;\n    initial begin\n"
                "        for (i=0;i<32;i=i+1) registers[i]=32'b0;\n"
                "    end\n",
                "",
                "register-file FPGA initialization",
            )
        if name == "controller":
            baseline = baseline.replace(
                "documented single-cycle RV32IM instruction subset",
                "documented RV32I instruction subset",
            )
        if name == "alu":
            baseline = baseline.replace("RV32I/RV32M", "RV32I")
        parts.append(baseline.rstrip())
    return parts


def generate(label, config, parts):
    if config is None:
        core = (ROOT / "CURRENT_multicycle" / "rtl" / "rv32i_multicycle.sv").read_text()
        core = replace_once(core, "    reg [3:0]  alu_op_reg;\n",
                            "    reg [3:0]  alu_op_reg;\n    reg        alu_src_reg;\n",
                            "baseline ALU source declaration")
        core = replace_once(core, "    reg alu_src_reg;\n", "",
                            "late ALU source declaration")
    else:
        core = (ROOT / "OPTIMIZED_multicycle" / "rtl" / "rv32i_multicycle.sv").read_text()
        core = replace_once(
            core,
            "module rv32i_multicycle #(\n"
            "    parameter PREDECODE = 1'b1,\n"
            "    parameter OR_SELECT = 1'b1\n"
            ") (",
            "module rv32i_multicycle (",
            "optimization parameters",
        )
        predecode, or_select = config
        core = replace_once(
            core, "    localparam [2:0] ST_FETCH",
            f"    localparam PREDECODE = 1'b{predecode};\n"
            f"    localparam OR_SELECT = 1'b{or_select};\n\n"
            "    localparam [2:0] ST_FETCH",
            "state declarations",
        )

    header = (
        f"// Standalone RV32I multi-cycle ASIC source: {label}.\n"
        "// Top module: rv32i_multicycle. External instruction and data memories.\n"
        "// Generated by generate_unified.py; do not edit this file directly.\n"
    )
    return header + "\n" + "\n\n".join([*parts, core.rstrip()]) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check outputs without writing")
    args = parser.parse_args()
    parts = shared_parts()
    for filename, label, config in CONFIGS:
        path = OUT / filename
        content = generate(label, config, parts)
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f"Out of date: {path}")
            print(f"OK {path.name}")
        else:
            path.write_text(content)
            print(f"Wrote {path.name}")


if __name__ == "__main__":
    main()
